import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import React from 'react';
import {transformWithOxc} from 'vite';
let receive,navigated=null;const logouts=[];
const frameWindow={};
const source=(await fs.readFile(new URL('../life-os-workspace.jsx',import.meta.url),'utf8')).replace(/^import .*;\n/gm,'').replace('export default function LifeOSWorkspace','function LifeOSWorkspace');
const transformed=await transformWithOxc(source,'workspace.jsx',{jsx:{runtime:'classic'}});
const context=vm.createContext({React,sb:null,useState:value=>[value,()=>{}],useRef:()=>({current:{contentWindow:frameWindow}}),useEffect:effect=>effect(),location:{origin:'https://lmrcapitals.com'},window:{addEventListener:(name,fn)=>{receive=fn;},removeEventListener:()=>{}}});
vm.runInContext(transformed.code+'\nthis.component=LifeOSWorkspace',context);
context.component({active:true,preview:true,onNavigate:route=>{navigated=route;},onSignOut:()=>logouts.push('local'),onSignOutEverywhere:()=>logouts.push('global')});
const valid={origin:'https://lmrcapitals.com',source:frameWindow,data:{type:'lmr-life-os-navigation',action:'settings'}};
for(const event of [{...valid,origin:'https://other.test'},{...valid,source:{}},{...valid,data:{...valid.data,action:'admin'}},{...valid,data:{type:'different',action:'settings'}}]){receive(event);assert.equal(navigated,null);}
receive(valid);assert.equal(navigated,'settings');
const signout={origin:valid.origin,source:frameWindow,data:{type:'lmr-life-os-signout',scope:'local'}};
for(const event of [{...signout,origin:'https://other.test'},{...signout,source:{}},{...signout,data:{...signout.data,scope:'other'}},{...signout,data:{type:'wrong',scope:'global'}}])receive(event);
assert.equal(logouts.length,0);
receive(signout);receive({...signout,data:{...signout.data,scope:'global'}});
assert.deepEqual(logouts,['local','global'],'Only authenticated parent owns logout/confirmation');

const lifeOs=await fs.readFile(new URL('../../life-os/LifeOS.jsx',import.meta.url),'utf8');
const body=lifeOs.slice(lifeOs.indexOf(' function signOut(scope){'),lifeOs.indexOf(' function toggle(id)'));
const messages=[];
const parent={postMessage:(message,origin)=>messages.push({message,origin})};
const controls={saving:{current:false},failed:{current:null},blocked:false,window:{parent},location:{origin:valid.origin,assign:()=>{throw new Error('Embedded logout should stay with parent');}}};
vm.runInNewContext(body,controls);
for(const scope of ['local','global'])controls.signOut(scope);
assert.deepEqual(messages.map(x=>x.message.scope),['local','global']);
assert.ok(messages.every(x=>x.origin===valid.origin));
controls.saving.current=true;controls.signOut('local');
controls.saving.current=false;controls.failed.current={attempted:true};controls.signOut('global');
controls.failed.current=null;controls.blocked=true;controls.signOut('local');
assert.equal(messages.length,2,'Pending/failed Life OS saves must not be discarded by logout');
console.log('PASS: Life OS settings navigation/logout accepts only the same-origin child frame, allowlists scopes, delegates confirmation to parent and protects pending/failed edits.');
